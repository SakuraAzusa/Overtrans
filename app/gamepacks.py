"""游戏 UI 布局预设 —— OverField 专用

这个游戏的 UI 位置固定，只有窗口尺寸会变，所以区域写死在代码里，不需要框选。

两处会出现玩家聊天：

1. 聊天面板（左侧，展开状态）
   频道标签 → 头像 → 昵称 → 气泡正文，纵向从顶部第一行铺到输入框上方。
   占满左侧整列，比例与窗口尺寸无关，可以直接用百分比。

2. 底部预览条（聊天框收起的行动/战斗模式）
   屏幕底部三条滚动预览，带「附近 |」频道标签和昵称前缀。
   **这组 UI 是底部对齐、按窗口宽度等比缩放的**，所以不能用固定百分比：
   窗口高度一变，占的百分比就跟着变（1920×1080 下三条在 y 72~92%，
   2560×1369 下在 y 81~95%）。用像素推算才稳。
"""

# ---------------------------------------------------------------- 采集区
# 聊天面板：左侧整列，比例固定
CHAT_PANEL = [0.148, 0.050, 0.420, 0.936]

# 底部预览条：从底部 UI 栏往上数三行，按窗口宽度推算（见 bottom_zone）
BOTTOM_X = (0.318, 0.676)          # 头像左沿 ~ 最长消息右端
BOTTOM_BAR_H = 0.026               # 底部功能栏（聊天/频道/生活/互动）高度 ÷ 窗口宽度
BOTTOM_LINE_H = 0.027              # 一行消息高度 ÷ 窗口宽度
BOTTOM_LINES = 3.3                 # 往上覆盖几行（3 条 + 余量）

# 聊天面板展开时，游戏会盖一层半透明白色遮罩，整块区域饱和度骤降。
# 实测：展开 15~20，收起（纯场景）138~142，阈值 60 分得很开。
PANEL_SAT_THRESHOLD = 60.0

# ---------------------------------------------------------------- 行为参数
MAX_OCR_PER_ROUND = 2          # 一轮最多识别几个区


def bottom_zone(width, height):
    """底部预览条的窗口内比例。

    游戏 UI 按窗口宽度等比缩放（图标、行高都是固定像素 × 宽度比），
    底部对齐。所以从下往上按宽度算像素，再换算成比例。

    实测对照：
      1920×1080 → [0.318, 0.789, 0.676, 0.954]，三条消息落在 82.5~91.8%
      2560×1369 → [0.318, 0.778, 0.676, 0.951]，三条消息落在 81.5~93.6%
    """
    bar = width * BOTTOM_BAR_H
    line = width * BOTTOM_LINE_H
    y1 = (height - bar) / height
    y0 = (height - bar - line * BOTTOM_LINES) / height
    return [BOTTOM_X[0], max(0.0, y0), BOTTOM_X[1], min(1.0, y1)]


def zones_for(width, height):
    """返回该窗口尺寸下实际使用的 [(key, name, ratio, priority), ...]"""
    return [
        ("chat", "聊天面板", list(CHAT_PANEL), 0),
        ("bottom", "底部预览", bottom_zone(width, height), 1),
    ]


def describe():
    """给界面显示用的一行摘要"""
    return "聊天面板 + 底部预览"


def panel_expanded(img):
    """聊天面板是否展开。

    展开时整块被半透明白色遮罩压住，饱和度很低；
    收起时这里是原始场景，颜色鲜艳。
    """
    import numpy as np

    arr = np.asarray(img.convert("HSV"), dtype=np.uint8)
    return float(arr[:, :, 1].mean()) < PANEL_SAT_THRESHOLD
